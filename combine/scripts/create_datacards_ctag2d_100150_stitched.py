def _table_sumw(kind_prefix, exact=False):
    """(era, group) -> sumw. For JES/JER kinds, all shift dirs must cover the same chunks
    (the dc loader applies one scale per sample to every shift), else raise."""
    kinds = [k for k in SUMW_TABLE if (k == kind_prefix if exact else k.startswith(kind_prefix + "/"))]
    if not kinds:
        raise RuntimeError(f"no '{kind_prefix}' entries in {CFG.sumw_table}")
    out = {}
    for k in kinds:
        for era, groups in SUMW_TABLE[k].items():
            for g, rec in groups.items():
                if rec["n_missing"]:
                    raise RuntimeError(f"sumw table: {rec['n_missing']} chunks without sumw in {k} {era} {g}")
                prev = out.get((era, g))
                if prev is not None and abs(prev - rec["sumw"]) > 1e-9 * abs(prev):
                    raise RuntimeError(f"sumw table: {k} {era} {g} sumw {rec['sumw']} != {prev} of another shift dir")
                out[(era, g)] = rec["sumw"]
    return out


def stitch_weight(variant, df):
    """Per-event stitching weight of `variant` for 4FS events (df needs n_chad5, n_chad10, gen_chad1_pt)."""
    if CFG.no_stitch_reweight:
        return np.ones(len(df))
    v = STITCH["variants"][variant]
    n = df[FS_VARIANT_COL[variant]].values
    lead = df["gen_chad1_pt"].values
    edges = np.array(STITCH["edges_gen_chad1_pt"], float)
    w3 = np.array([np.nan if x is None else x for x in v["w_3FS_region"]], float)
    b = np.clip(np.digitize(lead, edges) - 1, 0, len(w3) - 1)
    w3e = w3[b]
    in3 = n >= v["n_min_from_3FS"]
    if np.any(in3 & ~np.isfinite(w3e)):
        raise RuntimeError(f"stitch weight undefined for some 3FS-region events ({variant})")
    return np.where(in3, w3e, v["w_4FS_region"])


