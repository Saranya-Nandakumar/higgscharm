def ctag2d_weights(df, era, usable):
    """{nuisance: (weight_up, weight_down)} c-tag SF variations of the signal events (full
    weights, as rs._recompute_ctag2d_raw). Default: the single raw CMS_ctag2d; replaced by
    create_datacards_ctag2d_100150_stitched_decorr.py with the 33-source scheme (2026-10-15)."""
    if "CMS_ctag2d" not in usable:
        return {}
    return {"CMS_ctag2d": rs._recompute_ctag2d_raw(df, era)}


def load_signal_nominal(scales):
    """Signal (scores, weights, syst) for dc.finalize_mc_data, same systematic
    handling as rs.load_mc_scored_parquets_rawsf (CMS_ctag2d recomputed raw)."""
    usable = dc.USABLE_SYST["Signal"]
    scores, weights = [], []
    systw = defaultdict(lambda: defaultdict(list))
    raw_weight = 0.0
    ev = defaultdict(list)   # per-event record for signal_events.npz
    skip = set(FS_SYST_ACTIVE) | set(FS_PRESCRIBED_SYSTS) | set(SIG4FS_SCALE)
    for era in ERAS:
        cols_syst = [dc.syst_col(s, d, era) for s in usable if s not in skip for d in ("Up", "Down")]
        jet_cols = rs.jet_score_cols(era)   # PNet 2022/2023, UParTAK4 2024/2025 (2026-10-25)
        fsp = _STATE["summary"][era].get("fs_prescribed")
        chad_cols = (["n_chad5", "n_chad10", "gen_chad1_pt"] if CFG.signal_mode == "4fs_rw"
                     else ["n_chad10"] if SIG4FS_SCALE else [])
        for sample_name, piece, sdir in _signal_samples(era):
            c = scales[(era, piece)]
            sv_cols = [c_ for c_, _ in SCALE_POINTS] if (fsp and piece == "3FS") else []
            for pq_file in E.files(sdir, ".parquet"):
                df = E.read_parquet(pq_file, ["zz_mass_inclusive", "mva_score_Signal", "weight_nominal",
                                              "n_genc10"] + chad_cols + cols_syst + jet_cols + sv_cols).to_pandas()
                if "n_genc10" not in df.columns:
                    raise RuntimeError(f"no n_genc10 column: {pq_file}")
                fac_all = region_mask(piece, df["n_genc10"].values) * c
                if chad_cols:
                    missing = [k for k in chad_cols if k not in df.columns]
                    if missing:
                        raise RuntimeError(f"{pq_file}: no {missing} (needs the jecshifts_fschad production)")
                if CFG.signal_mode == "4fs_rw":
                    w_nom = stitch_weight(CFG.stitch_variant, df)
                    fs_ratio = {s: stitch_weight(v, df) / w_nom for s, v in FS_SYST_ACTIVE.items()}
                    fac_all = fac_all * w_nom
                raw_weight += (df["weight_nominal"].fillna(0).values * fac_all).sum()
                m = ((df["zz_mass_inclusive"] >= dc.MASS_WINDOW[0]) & (df["zz_mass_inclusive"] < dc.MASS_WINDOW[1])
                     & (df["mva_score_Signal"] >= 0))
                df = df[m]
                fac = fac_all[m.values]
                keep = fac != 0
                df, fac = df[keep], fac[keep]
                if CFG.signal_mode == "4fs_rw":
                    fs_ratio = {s: r[m.values][keep] for s, r in fs_ratio.items()}
                if len(df) == 0:
                    continue
                nom = df["weight_nominal"].fillna(0).values * fac
                scores.append(df["mva_score_Signal"].values)
                weights.append(nom)
                ev["score"].append(df["mva_score_Signal"].values)
                ev["weight"].append(nom)
                ev["n_genc10"].append(df["n_genc10"].values)
                ev["piece"].append(np.full(len(df), 0 if piece == "4FS" else 1))
                ev["era"].append(np.full(len(df), ERAS.index(era)))
                ctag = {}
                if all(j in df.columns for j in jet_cols):
                    ctag = {k: (u * fac, d * fac) for k, (u, d) in ctag2d_weights(df, era, usable).items()}
                if fsp:
                    for col, rec in fsp["scale_points"].items():
                        if piece == "3FS":
                            wv = df[col].fillna(0).values * fac
                        else:
                            wv = nom * rec["r_4FS_0c"]
                        systw[f"{FS_SCALE_TMP}_{col[len('weight_scalevar_'):]}"]["Up"].append(wv * rec["renorm"])
                    for d in ("Up", "Down"):
                        systw["CMS_FS_cH_K3"][d].append(nom * fsp["K3"][d][piece])
                if SIG4FS_SCALE:
                        cls1 = df["n_chad10"].values >= 1
                        for name, v in SIG4FS_SCALE.items():
                            for d, (r0, r1) in v.items():
                                systw[name][d].append(nom * np.where(cls1, r1, r0))
                for syst in usable:
                    if syst in FS_PRESCRIBED_SYSTS or syst in SIG4FS_SCALE:
                        continue
                    if syst in FS_SYST_ACTIVE:
                        r = fs_ratio[syst]
                        systw[syst]["Up"].append(nom * r)
                        systw[syst]["Down"].append(nom * (2.0 - r))
                        continue
                    for d in ("Up", "Down"):
                        col = dc.syst_col(syst, d, era)
                        if syst in ctag:
                            systw[syst][d].append(ctag[syst][0 if d == "Up" else 1])
                        elif col in df.columns:
                            systw[syst][d].append(df[col].fillna(0).values * fac)
                        else:   # CMS_eff_m_id: not in the jecshifts workflows
                            systw[syst][d].append(nom)
    events = {k: np.concatenate(v) for k, v in ev.items()}
    return scores, weights, systw, raw_weight, events


