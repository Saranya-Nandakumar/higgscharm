def _table_sumw_pershift(kind_prefix):
    """(shift, era, group) -> sumw, one entry per JES/JER shift dir (e.g. shift =
    'CMS_scale_j_2022Down'), for productions whose shift dirs cover different chunks."""
    out = {}
    for k in SUMW_TABLE:
        if not k.startswith(kind_prefix + "/"):
            continue
        shift = k.split("/", 1)[1]
        for era, groups in SUMW_TABLE[k].items():
            for g, rec in groups.items():
                if rec["n_missing"]:
                    raise RuntimeError(f"sumw table: {rec['n_missing']} chunks without sumw in {k} {era} {g}")
                out[(shift, era, g)] = rec["sumw"]
    if not out:
        raise RuntimeError(f"no '{kind_prefix}' entries in {CFG.sumw_table}")
    return out


def load_jecshifts_pershift(jecshifts_dir, sumw_by_shift):
    """Copy of dc.load_jecshifts_scored_parquets (same reads, window, MVA cut and printout) with
    one scale per (sample, shift dir) instead of one per sample: in jecshifts_scored_v2 a few
    ggZZ->tautau shift dirs miss 0.2-1.5% of the chunks, so one sumw for all shifts does not
    match their events (2026-10-05, a test; the shared dc loader is untouched; revert with
    create_datacards_ctag2d_100150_stitched.py.bak_20261005_jec_pershift; second-brain
    Notes/hczz-preveto-genc-sumw-and-jec-pershift-sumw-2026-10-05.md)."""
    from collections import defaultdict
    raw = defaultdict(lambda: defaultdict(lambda: defaultdict(lambda: {"scores": [], "weights": []})))
    raw_sum = defaultdict(lambda: defaultdict(lambda: defaultdict(float)))
    for era in ERAS:
        era_dir = os.path.join(jecshifts_dir, era)
        if not E.isdir(era_dir):
            print(f"  WARNING: jecshifts era dir not found: {era_dir}")
            continue
        year = dc.era_year(era)
        for sample_name in E.listdir(era_dir):
            proc = dc.get_process_from_path(sample_name)
            if proc is None or proc not in dc.JECSHIFTS_USABLE_PROCS:
                continue
            g = dc.norm_group(sample_name)
            for syst in dc.JECSHIFTS_SYSTEMATICS:
                for direction in ("Up", "Down"):
                    shift = f"{syst}_{year}{direction}"
                    cat_dir = os.path.join(era_dir, sample_name, "base", shift)
                    if not E.isdir(cat_dir):
                        continue
                    sw = sumw_by_shift.get((shift, era, g))
                    if not sw:
                        raise RuntimeError(f"no table sumw for ({shift}, {era}, {g}) [sample {sample_name}]")
                    scale = dc.group_xs_pb(era, g) * dc.LUMINOSITY_PB[era] / sw
                    for pq_file in E.files(cat_dir, ".parquet"):
                        df = E.read_parquet(pq_file, ["zz_mass_inclusive", "mva_score_Signal", "weight_nominal"]).to_pandas()
                        raw_sum[proc][syst][direction] += df["weight_nominal"].fillna(0).values.sum()
                        m = ((df["zz_mass_inclusive"] >= dc.MASS_WINDOW[0]) & (df["zz_mass_inclusive"] < dc.MASS_WINDOW[1])
                             & (df["mva_score_Signal"] >= 0))
                        df = df[m]
                        if len(df) == 0:
                            continue
                        raw[proc][syst][direction]["scores"].append(df["mva_score_Signal"].values)
                        raw[proc][syst][direction]["weights"].append(df["weight_nominal"].fillna(0).values * scale)
    jec_data = defaultdict(lambda: defaultdict(dict))
    print(f"\n  {'Process':<15} {'Systematic':<16} {'Dir':<6} {'n_files_sum':>12} {'in_win_yield':>14}")
    print("  " + "-" * 66)
    for proc in dc.JECSHIFTS_USABLE_PROCS:
        for syst in dc.JECSHIFTS_SYSTEMATICS:
            for direction in ("Up", "Down"):
                sl = raw[proc][syst][direction]["scores"]
                if not sl:
                    print(f"  WARNING: no jecshifts events for {proc}/{syst}{direction}")
                    jec_data[proc][syst][direction] = (np.array([]), np.array([]))
                    continue
                w = np.concatenate(raw[proc][syst][direction]["weights"])
                jec_data[proc][syst][direction] = (np.concatenate(sl), w)
                print(f"  {proc:<15} {syst:<16} {direction:<6} {raw_sum[proc][syst][direction]:>12.2f} {w.sum():>14.4f}")
    return jec_data


def load_jecshifts_with_stitched_signal(jecshifts_dir, sumw_by_group):
    procs = dc.JECSHIFTS_USABLE_PROCS
    dc.JECSHIFTS_USABLE_PROCS = procs - {"Signal"}
    try:
        if SUMW_TABLE:
            # own chunk coverage of every jecshifts shift dir (2026-10-05: per shift dir, see
            # load_jecshifts_pershift); / MUON_ID_SF = the missing muon ID SF
            # (flat across processes to 0.0005, Notes/hczz-fs-stitching-builder-step-f-2026-09-29.md sec. 4)
            tab = _table_sumw_pershift("jec")
            per = {(sh, era, g): sw / MUON_ID_SF[era] for (sh, era, g), sw in tab.items()}
            groups = {(era, g) for (_, era, g) in tab}
            varying = sorted({(era, g) for (era, g) in groups
                              if len({round(sw, 6) for (sh, e2, g2), sw in tab.items() if (e2, g2) == (era, g)}) > 1})
            print(f"  JES/JER backgrounds: sumw per shift dir from the table ({len(tab)} shift-era-groups, "
                  f"{len(groups)} era-groups, {len(varying)} with shift-dependent sumw: {varying}), muon ID SF folded in")
            jec = load_jecshifts_pershift(jecshifts_dir, per)
        else:
            jec = dc_load_jecshifts_orig(jecshifts_dir, sumw_by_group)
    finally:
        dc.JECSHIFTS_USABLE_PROCS = procs
    jec["Signal"] = load_signal_jecshifts(_STATE["scales"])
    return jec


def build_histograms_fs(mc_data, zx_scores, zx_weights, jec_data=None):
    """dc.build_histograms, then the per-bin envelope of the temporary per-point Signal
    templates becomes Signal_CMS_FS_cH_scale{Up,Down} (variance of the template that sets
    each bin); the temporary templates are dropped."""
    h, hv = dc_build_histograms_orig(mc_data, zx_scores, zx_weights, jec_data=jec_data)
    tmp = sorted(k for k in h if k.startswith(f"Signal_{FS_SCALE_TMP}_"))
    if not tmp:
        return h, hv
    if CFG.fs_scale_mode == "separate":
        nom = h["Signal"]
        print(f"\n  separate Signal scale nuisances ({CFG.fs_prescribed}): Signal {nom.sum():.5f}")
        for name, (pu, pd) in SEP_SCALE.items():
            for d, pt in (("Up", pu), ("Down", pd)):
                k = f"Signal_{FS_SCALE_TMP}_{pt}Up"
                h[f"Signal_{name}{d}"], hv[f"Signal_{name}{d}"] = h[k], hv[k]
                print(f"    {name + d:<22} {h[k].sum():.5f} ({h[k].sum() / nom.sum() - 1:+.4f})")
        out = _output_dir()
        if out:
            with open(os.path.join(out, "fs_scale_separate.json"), "w") as fh:
                json.dump({"nominal": nom.tolist(), "mode": CFG.fs_prescribed,
                           "points": {k[len('Signal_' + FS_SCALE_TMP) + 1:]: h[k].tolist() for k in tmp}}, fh, indent=1)
        for k in tmp:
            del h[k], hv[k]
        k3u, k3d = h["Signal_CMS_FS_cH_K3Up"].sum(), h["Signal_CMS_FS_cH_K3Down"].sum()
        print(f"  CMS_FS_cH_K3: Up {k3u / nom.sum() - 1:+.4f}  Down {k3d / nom.sum() - 1:+.4f}")
        return h, hv
    V = np.array([h[k] for k in tmp])
    VV = np.array([hv[k] for k in tmp])
    iu, idn = V.argmax(axis=0), V.argmin(axis=0)
    cols = np.arange(V.shape[1])
    nom = h["Signal"]
    up, dn = np.maximum(V[iu, cols], nom), np.minimum(V[idn, cols], nom)
    h["Signal_CMS_FS_cH_scaleUp"], h["Signal_CMS_FS_cH_scaleDown"] = up, dn
    hv["Signal_CMS_FS_cH_scaleUp"] = np.where(up == nom, hv["Signal"], VV[iu, cols])
    hv["Signal_CMS_FS_cH_scaleDown"] = np.where(dn == nom, hv["Signal"], VV[idn, cols])
    print(f"\n  CMS_FS_cH_scale ({CFG.fs_prescribed}): Signal {nom.sum():.5f}")
    for k in tmp:
        print(f"    {k[len('Signal_' + FS_SCALE_TMP) + 1:]:<14} {h[k].sum():.5f} ({h[k].sum() / nom.sum() - 1:+.4f})")
        del h[k], hv[k]
    print(f"    envelope Up {up.sum():.5f} ({up.sum() / nom.sum() - 1:+.4f})  "
          f"Down {dn.sum():.5f} ({dn.sum() / nom.sum() - 1:+.4f})")
    k3u, k3d = h["Signal_CMS_FS_cH_K3Up"].sum(), h["Signal_CMS_FS_cH_K3Down"].sum()
    print(f"  CMS_FS_cH_K3: Up {k3u / nom.sum() - 1:+.4f}  Down {k3d / nom.sum() - 1:+.4f}")
    out = _output_dir()
    if out:
        with open(os.path.join(out, "fs_scale_envelope.json"), "w") as fh:
            json.dump({"nominal": nom.tolist(), "up": up.tolist(), "down": dn.tolist(),
                       "points": {k[len('Signal_' + FS_SCALE_TMP) + 1:]: V[j].tolist() for j, k in enumerate(tmp)},
                       "mode": CFG.fs_prescribed}, fh, indent=1)
    return h, hv


def write_datacard_fs(histograms, root_filename, output_dir, include_zx=True, automcstats_threshold=None):
    """dc.write_datacard, then the Signal column of QCDscale_gg is removed; shape mode adds
    QCDscale_ccH (MiNNLOPS 4FS NNLO +4.4/-2.7%, LHCHWG-2026-007 Table 3) on Signal. With
    --pdf-ch the Signal column of pdf_gg moves to its own pdf_cH row (2026-10-12)."""
    path = dc_write_datacard_orig(histograms, root_filename, output_dir, include_zx=include_zx,
                                  automcstats_threshold=automcstats_threshold)
    lines = open(path).read().split("\n")
    procs = next(l.split()[1:] for l in lines if l.startswith("process") and not l.split()[1].lstrip("-").isdigit())
    isig = procs.index("Signal")
    out = []
    for l in lines:
        tok = l.split()
        if tok and tok[0] == "pdf_gg" and CFG.pdf_ch:
            vals = tok[2:]
            vals[isig] = "-"
            out.append(f"{tok[0]:<25}{tok[1]:<8}" + "".join(f"{v:<{max(12, len(v) + 1)}}" for v in vals).rstrip())
            cc = ["-"] * len(procs)
            cc[isig] = CFG.pdf_ch
            out.append(f"{'pdf_cH':<25}{'lnN':<8}" + "".join(f"{v:<{max(12, len(v) + 1)}}" for v in cc).rstrip())
            continue
        if tok and tok[0] == "QCDscale_gg":
            vals = tok[2:]
            vals[isig] = "-"
            name, stype = tok[0], tok[1]
            w = len(l) - len(l.lstrip())
            out.append(f"{name:<25}{stype:<8}" + "".join(f"{v:<{max(12, len(v) + 1)}}" for v in vals).rstrip())
            if CFG.fs_prescribed == "shape":
                cc = ["-"] * len(procs)
                cc[isig] = "0.973/1.044"
                out.append(f"{'QCDscale_ccH':<25}{'lnN':<8}" + "".join(f"{v:<12}" for v in cc).rstrip())
            continue
        out.append(l)
        if tok and tok[0] == "QCDscale_qqZZ" and CFG.higgs_scale_norm:
            rows = {}
            for p_, (name, val) in HIGGS_QCDSCALE.items():
                if p_ in procs:
                    rows.setdefault(name, ["-"] * len(procs))[procs.index(p_)] = val
            for name, vals in rows.items():
                out.append(f"{name:<25}{'lnN':<8}" + "".join(f"{v:<{max(12, len(v) + 1)}}" for v in vals).rstrip())
    open(path, "w").write("\n".join(out))
    if CFG.higgs_scale_norm:
        print(f"  datacard: Higgs QCDscale lnN rows added ({sorted(set(n for n, _ in HIGGS_QCDSCALE.values()))})")
    print(f"  datacard: QCDscale_gg removed from Signal"
          + ("; QCDscale_ccH 0.973/1.044 added" if CFG.fs_prescribed == "shape" else "")
          + (f"; Signal pdf_gg -> pdf_cH {CFG.pdf_ch}" if CFG.pdf_ch else ""))
    return path


